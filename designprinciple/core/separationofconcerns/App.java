package designprinciple.core.separationofconcerns;

//  Separation of Concerns (SoC) Principle:

//  Separation of Concerns means each part of your system should have one well-defined responsibility
//  and should not mix different types of logic.
//  A concern is a logical axis of responsibility.
//  SoC demands that each module handles one axis of responsibility end-to-end and does not leak into others.

//  Typical concerns:
//  Business rules, UI/Presentation, Data persistence, Logging, Error handling, Authorization & authentication
//  Networking, Cache layer, Infrastructure, Monitoring, Background jobs, Validation, Integration logic, Analytics
//  These should not be mixed.

//  SRP is micro-level ? within classes.
//  SoC is system-level ? architecture & module boundaries.

