package designprinciple.core.boundariesandencapsulation;

//  Definition:
//  A system is easy to evolve only when its internal details are hidden behind well-defined boundaries,
//  and each module exposes only what the outside world must know, nothing more.

//  Encapsulation = hide internal details
//  Boundaries = define how others interact with you
//  Together they ensure: Stable interfaces, flexible internals.
//  Boundaries & Encapsulation are core to scalable engineering.

//  This principle is about: Visibility control, Minimizing surface area, Preventing ripple effects
//  Reducing cognitive load, Allowing teams to work independently.

//  The Ripple Effect occurs when a small change in one module forces changes across many other modules,
//  revealing tight coupling, leaky boundaries, and poor encapsulation.
//  Surface area = the amount of API, behavior, data, and internal details that other modules/teams can see or depend on.
//  Cognitive load = how much a developer must think about to understand, modify, or use a module.
//  Reducing cognitive load ? Reduces what they need to understand.

